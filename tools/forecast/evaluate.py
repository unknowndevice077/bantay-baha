"""Evaluate the exported forecaster on held-out storms and write docs/forecast-results.md.

Scores public/forecast/model.json itself (inference re-implemented from the
JSON, exactly as the browser does it) on the test storms (id % 5 == 0), next to:
  * persistence  - "the level stays where it is"
  * trend        - "the last 10 minutes' rise continues"
  * ridge        - the linear baseline, refit here on the training storms

    python tools/forecast/evaluate.py
"""
import json
from datetime import date
from pathlib import Path

import numpy as np
from sklearn.linear_model import Ridge
from sklearn.preprocessing import StandardScaler

from features import FEATURES, HORIZONS_MIN, build, features_at
from generate_dataset import load
from train import MODEL_OUT, ROOT, split

DOC = ROOT / "docs" / "forecast-results.md"
THRESHOLDS = [("ADVISORY", 2.0), ("WARNING", 2.8), ("EVACUATE", 3.3)]


def status(level: np.ndarray) -> np.ndarray:
    out = np.zeros(level.shape, dtype=int)
    for k, (_, t) in enumerate(THRESHOLDS):
        out[level >= t] = k + 1
    return out


def json_predict(spec: dict, x: np.ndarray) -> np.ndarray:
    m = spec["model"]
    if m["type"] == "ridge":
        z = (x - np.array(m["mean"])) / np.array(m["scale"])
        return z @ np.array(m["coef"]).T + np.array(m["intercept"])
    cols = []
    for h in m["horizons"]:
        acc = np.full(len(x), h["init"])
        for tree in h["trees"]:
            f, t, l, r, v = (np.array(tree[k]) for k in "ftlrv")
            node = np.zeros(len(x), dtype=int)
            for _ in range(32):
                leaf = l[node] == -1
                if leaf.all():
                    break
                go_left = x[np.arange(len(x)), np.maximum(f[node], 0)] <= t[node]
                node = np.where(leaf, node, np.where(go_left, l[node], r[node]))
            acc += h["lr"] * v[node]
        cols.append(acc)
    return np.column_stack(cols)


def mae(pred, y):
    return np.mean(np.abs(pred - y), axis=0)


def lead_times(spec, storms, test_ids, threshold=2.8, horizon=60):
    """Per test storm reaching `threshold`: minutes between the forecast first
    expecting the crossing within `horizon` min and the actual crossing. Also
    counts storms that never reached it but were forecast to (false alarms)."""
    leads, false_alarms, quiet = [], 0, 0
    for sid in test_ids:
        obs, true, rain = storms[sid]
        n = len(obs) - max(HORIZONS_MIN)
        x = np.array([features_at(obs, rain, i) for i in range(10, n)])
        pred = obs[10:n, None] + json_predict(spec, x)
        warned = np.where((pred >= threshold).any(axis=1) & (obs[10:n] < threshold))[0]
        crossed = np.where(true >= threshold)[0]
        if len(crossed):
            first_warn = warned[0] + 10 if len(warned) else crossed[0]
            leads.append(max(0, crossed[0] - first_warn))
        else:
            quiet += 1
            false_alarms += int(len(warned) > 0)
    return np.array(leads), false_alarms, quiet


def main():
    spec = json.loads(MODEL_OUT.read_text())
    assert spec["features"] == FEATURES, "model.json was trained on different features; re-run train.py"
    storms = load()
    x, y, ids = build(storms)
    tr, _, te = split(ids)
    xt, yt = x[te], y[te]
    lvl = xt[:, FEATURES.index("level_m")]
    d10 = xt[:, FEATURES.index("d10_m")]

    scaler = StandardScaler().fit(x[tr])
    ridge = Ridge(alpha=1.0).fit(scaler.transform(x[tr]), y[tr])
    preds = {
        "Persistence (no change)": np.zeros_like(yt),
        "Trend (last 10 min continues)": np.column_stack([d10 * h / 10 for h in HORIZONS_MIN]),
        "Ridge regression": ridge.predict(scaler.transform(xt)),
        f"Exported model ({spec['model']['type']})": json_predict(spec, xt),
    }
    model_name = list(preds)[-1]
    rising = yt[:, 0] > 0.10
    high = lvl >= 2.0
    true_status = [status(lvl + yt[:, k]) for k in range(len(HORIZONS_MIN))]

    rows = []
    for name, p in preds.items():
        all_mae = mae(p, yt) * 100
        rise_mae = mae(p[rising], yt[rising]) * 100
        high_mae = mae(p[high], yt[high]) * 100
        acc = [np.mean(status(lvl + p[:, k]) == true_status[k]) * 100 for k in range(len(HORIZONS_MIN))]
        rows.append((name, *all_mae, *rise_mae, *high_mae, *acc))

    test_ids = sorted(set(ids[te].tolist()))
    leads, fa, quiet = lead_times(spec, storms, test_ids)
    # Auto-Storm (storm 0): the profile the simulator itself plays.
    x0, y0, _ = build([storms[0]])
    auto_mae = mae(json_predict(spec, x0), y0) * 100
    auto_persist = mae(np.zeros_like(y0), y0) * 100

    best = rows[-1]
    persist = rows[0]
    lines = [
        "# Forecast results",
        "",
        f"Generated by `python tools/forecast/evaluate.py` on {date.today().isoformat()}. "
        "Re-run `generate_dataset.py`, `train.py` and `evaluate.py` to reproduce (all seeded).",
        "",
        "## What is predicted",
        "",
        "The water level 30 and 60 minutes ahead, from the last 30 minutes of sensor readings and rainfall "
        "(features: " + ", ".join(f"`{f}`" for f in FEATURES) + "). The forecaster does **not** know future rainfall, "
        "which is where most of the remaining error comes from.",
        "",
        "## Data",
        "",
        f"- {len(storms)} synthetic storms (seed 2026) run through the simulator's own catchment model "
        "(`src/sim.ts`: linear reservoir, 10 s steps), sampled each minute, with the sensor's ±3 mm jitter.",
        "- Profiles: the Auto-Storm typhoon band (exact, and time/intensity-rescaled), two-band storms, flash floods, long drizzles; "
        "gusty rain wobble; wet or dry starting creek.",
        f"- Split by storm, never by minute: {len(set(ids[tr].tolist()))} train, "
        f"{len(set(ids[ids % 5 == 1].tolist()))} validation (model selection), {len(test_ids)} test (this report). "
        f"{len(yt):,} test samples.",
        "",
        "## Accuracy on held-out storms",
        "",
        "MAE = mean absolute error of the predicted level, in cm. *Rising* = samples where the creek actually rose more "
        "than 10 cm in the next 30 min. *High water* = samples already at ADVISORY or above. "
        "*Status* = predicted NORMAL / ADVISORY / WARNING / EVACUATE matches the true status at that time.",
        "",
        "| Method | MAE +30 | MAE +60 | MAE +30 rising | MAE +60 rising | MAE +30 high water | MAE +60 high water | Status +30 | Status +60 |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for r in rows:
        name = f"**{r[0]}**" if r is best else r[0]
        lines.append(f"| {name} | " + " | ".join(f"{v:.1f} cm" for v in r[1:7]) + " | " + " | ".join(f"{v:.1f} %" for v in r[7:9]) + " |")
    improve = [(1 - best[k] / persist[k]) * 100 for k in (1, 2)]
    lines += [
        "",
        f"The exported model cuts the error of the naive persistence forecast by {improve[0]:.0f} % at +30 min and "
        f"{improve[1]:.0f} % at +60 min.",
        "",
        "## Warning lead time",
        "",
        "For each test storm that reached WARNING (280 cm): how long before the actual crossing the forecast first said "
        "\"WARNING within the next 60 minutes\".",
        "",
        f"- Storms reaching WARNING: {len(leads)}; median lead time **{np.median(leads):.0f} min** "
        f"(25th percentile {np.percentile(leads, 25):.0f} min, 75th {np.percentile(leads, 75):.0f} min).",
        f"- Storms that never reached WARNING: {quiet}; the forecast predicted WARNING at some point in {fa} of them "
        f"({fa / max(1, quiet) * 100:.0f} % false-alarm rate).",
        "",
        "## The simulator's Auto-Storm",
        "",
        f"On the exact storm the simulator plays (storm 0, a training storm, so optimistic): MAE {auto_mae[0]:.1f} cm at +30 min "
        f"and {auto_mae[1]:.1f} cm at +60 min, vs {auto_persist[0]:.1f} / {auto_persist[1]:.1f} cm for persistence.",
        "",
        "## Limits",
        "",
        "- Synthetic data from the same model that drives the simulator: real creeks have backwater, debris jams, "
        "upstream releases and rating changes this does not capture. Retrain on recorded sensor data before relying on it.",
        "- No rainfall forecast is used. Feeding PAGASA nowcasts would reduce the +60 min error most.",
        "- See [failure-modes.md](failure-modes.md) for how the app behaves when the forecast is wrong or unavailable.",
        "",
    ]
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(lines), encoding="utf8")
    print("\n".join(lines[16:16 + len(rows) + 2]))
    print(f"lead time median {np.median(leads):.0f} min over {len(leads)} storms; false alarms {fa}/{quiet}")
    print(f"wrote {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
